fn step_ensure_capability(root: &ProjectRoot, force: bool) -> CoreResult<StepResult> {
    let mut missing = Vec::new();
    for p in DISCOVER_PATHS {
        if !path_exists(root, p)? {
            missing.push(*p);
        }
    }
    if missing.is_empty() {
        return Ok(StepResult {
            id: "ensure_capability_discover".to_string(),
            status: "skipped".to_string(),
            paths: DISCOVER_PATHS.iter().map(|s| (*s).to_string()).collect(),
        });
    }
    // Re-run installs to materialize matrix outputs (includes dare-discover).
    let _ = install_commands(root, force)?;
    let _ = install_cursor_commands(root, force)?;
    let _ = install_codex_skills(root, force)?;
    let _ = install_antigravity(root, force)?;
    for p in DISCOVER_PATHS {
        if !path_exists(root, p)? {
            return Err(CoreError::config(format!(
                "dare-discover capability missing after install: {p}"
            )));
        }
    }
    Ok(StepResult {
        id: "ensure_capability_discover".to_string(),
        status: "updated".to_string(),
        paths: DISCOVER_PATHS.iter().map(|s| (*s).to_string()).collect(),
    })
}

