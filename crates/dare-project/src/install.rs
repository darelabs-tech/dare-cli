/// Apply an install plan under `root`.
pub fn apply_install(
    root: &ProjectRoot,
    plan: &InstallPlan,
    opts: &InstallOptions,
) -> CoreResult<InstallReport> {
    if opts.dry_run {
        return Ok(empty_report(plan, true));
    }

    let mut journal = SessionJournal::default();
    let mut created = Vec::new();
    let mut updated = Vec::new();
    let mut skipped = Vec::new();
    let mut backed_up = Vec::new();
    let result = (|| -> CoreResult<(Vec<StepResult>, Vec<String>)> {
        let mut acc = PathAcc {
            created: &mut created,
            updated: &mut updated,
            skipped: &mut skipped,
            backed_up: &mut backed_up,
        };
        #[allow(clippy::vec_init_then_push)]
        let steps = {
            let mut steps = Vec::new();
            steps.push(step_ensure_dirs(root, &mut journal)?);
            steps.push(step_write_config(root, plan, opts, &mut journal, &mut acc)?);
            steps.push(step_templates(root, opts, &mut journal, &mut acc)?);
            steps.push(step_graph(root, &mut journal, &mut acc)?);
            steps.push(step_gitignore(root, &mut journal, &mut acc)?);
            steps.push(step_harness_claude(root, opts.force)?);
            steps.push(step_harness_cursor(root, opts.force)?);
            steps.push(step_harness_codex(root, opts.force)?);
            steps.push(step_harness_antigravity(root, opts.force)?);
            steps.push(step_ensure_capability(root, opts.force)?);
            steps.push(step_validate(root)?);
            steps
        };
        let harnesses_validated = vec![
            "antigravity".to_string(),
            "claude".to_string(),
            "codex".to_string(),
            "cursor".to_string(),
        ];
        Ok((steps, harnesses_validated))
    })();

    let (steps, harnesses_validated) = match result {
        Ok(v) => v,
        Err(e) => {
            let _ = rollback(root, &journal);
            return Err(e);
        }
    };
    sort_unique(&mut created);
    sort_unique(&mut updated);
    sort_unique(&mut skipped);
    sort_unique(&mut backed_up);

    Ok(InstallReport {
        schema_version: INSTALL_SCHEMA_VERSION,
        mode: "install".to_string(),
        project_root: plan.project_root.to_string_lossy().replace('\\', "/"),
        steps,
        created,
        updated,
        skipped,
        backed_up,
        harnesses_validated,
        conflicts: plan.conflicts.clone(),
        warnings: plan.warnings.clone(),
        dry_run: false,
    })
}

/// Detect → plan → apply.
pub fn install(start: &Path, opts: &InstallOptions) -> CoreResult<InstallReport> {
    if !start.exists() || !start.is_dir() {
        return Err(CoreError::not_found(format!(
            "directory not found: {}",
            start.display()
        )));
    }
    let detection = detect(start)?;
    let plan = plan_install(&detection, opts)?;
    let root = ProjectRoot::new(&plan.project_root)?;
    apply_install(&root, &plan, opts)
}

